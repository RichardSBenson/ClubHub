import * as Q from './domain/qualification.mjs';
let pass = 0, fail = 0;
const ok = (n, c, d = '') => c ? (pass++, console.log(`  ✓ ${n}`)) : (fail++, console.log(`  ✗ ${n}  ${d}`));
const today = '2026-10-02';
console.log('\nSTATUS');
ok('no expiry is permanent', Q.statusOf(null, today) === 'permanent');
ok('past is expired', Q.statusOf('2026-10-01', today) === 'expired');
ok('today is not yet expired, and is expiring', Q.statusOf(today, today) === 'expiring');
ok('59 days is expiring', Q.statusOf('2026-11-30', today) === 'expiring');
ok('60 days is current', Q.statusOf('2026-12-01', today) === 'current');
ok('days left', Q.daysLeft('2026-10-12', today) === 10 && Q.daysLeft('2026-09-30', today) === -2 && Q.daysLeft(null, today) === null);
console.log('\nWHICH AWARD COUNTS');
const aw = (id, q, exp, on = '2023-01-01', person = 'p') => ({ id, person_id: person, qualification_id: q, expires_on: exp, awarded_on: on });
const l = Q.latestPerQualification([aw('a', 'fa', '2025-01-01'), aw('b', 'fa', '2028-01-01'), aw('c', 'vet', '2024-01-01'), aw('d', 'fa', '2027-01-01')]);
ok('the latest expiry wins', l.find((x) => x.qualification_id === 'fa').id === 'b' && l.length === 2);
ok('never-expires beats a dated one', Q.latestPerQualification([aw('a', 'x', '2030-01-01'), aw('b', 'x', null)])[0].id === 'b');
ok('different people stay separate', Q.latestPerQualification([aw('a', 'x', '2030-01-01', '2023-01-01', 'p1'), aw('b', 'x', '2020-01-01', '2023-01-01', 'p2')]).length === 2);
console.log('\nCLEARANCE');
const need = [{ id: 'fa', label: 'First aid' }, { id: 'vet', label: 'Police vetting' }];
let c = Q.clearance(need, [aw('a', 'fa', '2028-01-01'), aw('b', 'vet', '2029-01-01')], today);
ok('all current is cleared', c.cleared && c.barred.length === 0 && c.warnings.length === 0);
c = Q.clearance(need, [aw('a', 'fa', '2026-10-20'), aw('b', 'vet', '2029-01-01')], today);
ok('expiring is a warning, not a bar', c.cleared && c.warnings.length === 1 && c.warnings[0].label === 'First aid');
c = Q.clearance(need, [aw('a', 'fa', '2025-01-01'), aw('b', 'vet', '2029-01-01')], today);
ok('expired is a bar', !c.cleared && c.barred[0].state === 'expired');
c = Q.clearance(need, [aw('b', 'vet', '2029-01-01')], today);
ok('missing is a bar', !c.cleared && c.barred[0].state === 'missing' && c.barred[0].label === 'First aid');
ok('a renewal clears an old expiry', Q.clearance(need, [aw('a', 'fa', '2025-01-01'), aw('n', 'fa', '2029-01-01'), aw('b', 'vet', null)], today).cleared);
ok('nothing required means cleared', Q.clearance([], [], today).cleared);
console.log('\nREMINDERS');
const latest = [aw('e1', 'fa', '2026-11-01'), aw('e2', 'fa', '2026-09-20'), aw('e3', 'fa', '2023-01-01'), aw('e4', 'fa', '2030-01-01'), aw('e5', 'fa', null)];
const due = Q.remindersDue(latest, today);
ok('expiring and recently expired are reminded', due.length === 2 && due.some((d) => d.awardId === 'e1' && d.stage === 'expiring') && due.some((d) => d.awardId === 'e2' && d.stage === 'expired'));
ok('long expired, distant and permanent are not', !due.some((d) => ['e3', 'e4', 'e5'].includes(d.awardId)));
ok('never twice', Q.remindersDue(latest, today, new Set(['e1|expiring', 'e2|expired'])).length === 0);
ok('wording names the thing and the date', /First aid.*2026-11-01/.test(Q.reminderText('expiring', { label: 'First aid', expiresOn: '2026-11-01' }).subject));
console.log('\nFORMS');
const r = Q.readQualification({ label: ' First  Aid ', validMonths: '36', for_instruct: '1', for_panel: '1' });
ok('read: code from label, required-for ticks', r.code === 'first-aid' && r.requiredFor.join() === 'instruct,panel' && r.validMonths === '36');
ok('a qualification needs a name', Q.problemsWithQualification({ ...r, label: '', code: '' }).length === 2);
ok('months must be sensible', Q.problemsWithQualification({ ...r, validMonths: '0' }).length === 1 && Q.problemsWithQualification({ ...r, validMonths: '2.5' }).length === 1 && Q.problemsWithQualification({ ...r, validMonths: '' }).length === 0);
ok('an award needs real dates', Q.problemsWithAward({ qualificationId: 'x', awardedOn: '2026-02-30', expiresOn: '' }, today).length === 1);
ok('month 13 is a problem, not a crash', Q.problemsWithAward({ qualificationId: 'x', awardedOn: '2026-13-01' }, today).length === 1);
ok('not issued in the future', Q.problemsWithAward({ qualificationId: 'x', awardedOn: '2027-01-01' }, today).length === 1);
ok('not expiring before issue', Q.problemsWithAward({ qualificationId: 'x', awardedOn: '2026-01-01', expiresOn: '2025-01-01' }, today).length === 1);
ok('a good award is fine', Q.problemsWithAward({ qualificationId: 'x', awardedOn: '2026-01-01', expiresOn: '2029-01-01' }, today).length === 0);
ok('starters are well formed', Q.STARTERS.every((s) => Q.problemsWithQualification({ ...s, validMonths: s.validMonths ? String(s.validMonths) : '' }).length === 0));
console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
