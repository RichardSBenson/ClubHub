import { parseCsv, publishable } from './domain/register-csv.mjs';
let pass = 0, fail = 0;
const ok = (n, c, d = '') => c ? (pass++, console.log(`  ✓ ${n}`)) : (fail++, console.log(`  ✗ ${n}  ${d}`));
console.log('\nREADING');
const a = parseCsv('slug,name\nwellington,Wellington\nhornby,"Hornby, Christchurch"');
ok('commas', a.length === 2 && a[1].name === 'Hornby, Christchurch');
const b = parseCsv('slug\tname\nwellington\tWellington');
ok('tabs, as pasted from a spreadsheet', b.length === 1 && b[0].slug === 'wellington' && b[0].name === 'Wellington');
const c = parseCsv('﻿slug,name\r\nx,Y\r\n');
ok('a hidden file-start mark and Windows line ends', c.length === 1 && c[0].slug === 'x' && c[0].name === 'Y', JSON.stringify(c));
ok('the column names are kept', JSON.stringify(a.columns) === '["slug","name"]');
ok('blank stays blank', parseCsv('slug,phone\nx,')[0].phone === '');
ok('a file with only a header has no rows but has columns', parseCsv('slug,name').length === 0 && parseCsv('slug,name').columns.length === 2);
console.log('\nPUBLISHING');
ok('everything a visitor needs', publishable({ venue_name: 'V', address_line: 'A', phone: '1' }, 1).length === 0);
ok('no venue is named', publishable({ address_line: 'A', phone: '1' }, 1).join() === 'venue');
ok('no class times is named', publishable({ venue_name: 'V', suburb: 'S', email: 'e' }, 0).join() === 'training times');
console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
